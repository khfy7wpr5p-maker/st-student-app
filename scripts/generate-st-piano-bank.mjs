import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SAMPLE_RATE = 44_100;
const DURATION_FRAMES = 110_250;
const DURATION_SECONDS = DURATION_FRAMES / SAMPLE_RATE;
const NAMES = Object.freeze([
  "C4", "Cs4", "D4", "Ds4", "E4", "F4",
  "Fs4", "G4", "Gs4", "A4", "As4", "B4",
]);
const PARTIALS = Object.freeze([
  [1, 1.00, 1.00],
  [2, 0.46, 1.35],
  [3, 0.23, 1.75],
  [4, 0.13, 2.15],
  [5, 0.08, 2.60],
  [6, 0.05, 3.10],
]);
const INHARMONICITY = 0.00035;

function writeWav(midi) {
  const frequency = 440 * (2 ** ((midi - 69) / 12));
  const raw = new Float64Array(DURATION_FRAMES);
  let peak = 0;

  for (let frame = 0; frame < DURATION_FRAMES; frame += 1) {
    const t = frame / SAMPLE_RATE;
    const attack = Math.min(1, t / 0.006);
    const decay = Math.exp(-2.2 * t);
    const release =
      t < 2.2 ? 1 : Math.max(0, (DURATION_SECONDS - t) / 0.3);

    let sum = 0;
    for (const [n, amplitude, damping] of PARTIALS) {
      sum +=
        amplitude *
        Math.exp(-damping * 0.22 * t) *
        Math.sin(
          2 *
            Math.PI *
            frequency *
            n *
            Math.sqrt(1 + INHARMONICITY * n * n) *
            t,
        );
    }

    const value = attack * decay * release * sum;
    raw[frame] = value;
    peak = Math.max(peak, Math.abs(value));
  }

  const dataBytes = DURATION_FRAMES * 2;
  const buffer = Buffer.alloc(44 + dataBytes);
  buffer.write("RIFF", 0, "ascii");
  buffer.writeUInt32LE(36 + dataBytes, 4);
  buffer.write("WAVE", 8, "ascii");
  buffer.write("fmt ", 12, "ascii");
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(SAMPLE_RATE, 24);
  buffer.writeUInt32LE(SAMPLE_RATE * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write("data", 36, "ascii");
  buffer.writeUInt32LE(dataBytes, 40);

  const scale = peak > 0 ? 0.82 / peak : 0;
  for (let frame = 0; frame < DURATION_FRAMES; frame += 1) {
    const normalized = Math.max(-1, Math.min(1, raw[frame] * scale));
    buffer.writeInt16LE(
      Math.round(normalized * 32767),
      44 + frame * 2,
    );
  }

  return buffer;
}

const root = fileURLToPath(new URL("../vendor/st-piano/", import.meta.url));
const samplesRoot = fileURLToPath(
  new URL("../vendor/st-piano/samples/", import.meta.url),
);
await mkdir(samplesRoot, { recursive: true });

const manifestSamples = [];
for (let index = 0; index < NAMES.length; index += 1) {
  const midi = 60 + index;
  const file = `samples/${NAMES[index]}.wav`;
  const buffer = writeWav(midi);

  await writeFile(
    new URL(`../vendor/st-piano/${file}`, import.meta.url),
    buffer,
  );

  manifestSamples.push({
    midi,
    file,
    bytes: buffer.length,
    sha256: createHash("sha256").update(buffer).digest("hex"),
  });
}

const manifest = {
  schemaVersion: 1,
  generator: "scripts/generate-st-piano-bank.mjs",
  format: "audio/wav; codecs=1",
  sampleRate: SAMPLE_RATE,
  channels: 1,
  bitsPerSample: 16,
  durationFrames: DURATION_FRAMES,
  samples: manifestSamples,
};

await writeFile(
  new URL("../vendor/st-piano/runtime-manifest.json", import.meta.url),
  JSON.stringify(manifest, null, 2) + "\n",
  "utf8",
);

await writeFile(
  new URL("../vendor/st-piano/LICENSE.txt", import.meta.url),
  [
    "ST Piano Generated Audio Asset License",
    "",
    "These audio files are deterministically generated by this repository and contain no third-party audio recordings.",
    "Permission is granted to use, copy, modify, bundle, and redistribute these generated audio assets as part of SesliTab and distributions derived from this repository, including commercial distributions.",
    "",
  ].join("\n"),
  "utf8",
);

await writeFile(
  new URL("../vendor/st-piano/THIRD_PARTY_NOTICES.md", import.meta.url),
  [
    "# ST Piano third-party notices",
    "",
    "No third-party audio content is included.",
    "",
    "All WAV files are generated deterministically by `scripts/generate-st-piano-bank.mjs`.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`generated ${manifestSamples.length} samples in ${root}`);
